"""
Helpers shared by every SPICE-driving script.

* locating ngspice
* building a parametrised copy of the model card, so process parameters
  (vth0, toxe, ndep, u0, xj) become .param variables for each sample/corner
* running many small circuits in one ngspice process (batch mode with
  `source <file>` / `op` / `print` / `remcirc` in a .control block)
"""
import os
import re
import shutil
import subprocess
from pathlib import Path

import config

# ----------------------------------------------------------------------------
# ngspice location
# ----------------------------------------------------------------------------
_NGSPICE_CANDIDATES = [
    os.environ.get("NGSPICE", ""),
    r"D:\JAYAKANTH FOLDER\ngspice-44.2_64\Spice64\bin\ngspice_con.exe",
    str(config.TOOLS_DIR / "ngspice" / "Spice64" / "bin" / "ngspice_con.exe"),
]


def find_ngspice() -> str:
    for c in _NGSPICE_CANDIDATES:
        if c and Path(c).is_file():
            return c
    on_path = shutil.which("ngspice_con") or shutil.which("ngspice")
    if on_path:
        return on_path
    raise FileNotFoundError(
        "ngspice not found. Set the NGSPICE environment variable to ngspice_con.exe")


def ngspice_version(exe: str) -> str:
    out = subprocess.run([exe, "-v"], capture_output=True, text=True).stdout
    m = re.search(r"ngspice-[\w.]+", out)
    return m.group(0) if m else "unknown"


# ----------------------------------------------------------------------------
# Parametrised model card
# ----------------------------------------------------------------------------
def read_nominal_params(model_file: Path = config.MODEL_FILE) -> dict:
    """Return {'nmos': {...}, 'pmos': {...}} nominal values of PROC_PARAMS."""
    text = model_file.read_text()
    out = {}
    for block in re.split(r"(?im)^(?=\.model)", text):
        m = re.match(r"(?i)\.model\s+(\w+)", block)
        if not m:
            continue
        dev = m.group(1).lower()
        out[dev] = {}
        for p in config.PROC_PARAMS:
            mm = re.search(r"(?i)(?<![\w])%s\s*=\s*([-+0-9.eE]+)" % p, block)
            out[dev][p] = float(mm.group(1))
    return out


def write_param_model(dest: Path, model_file: Path = config.MODEL_FILE) -> Path:
    """
    Copy the model card, replacing each PROC_PARAM value with {p_n_<name>} for
    the nmos model and {p_p_<name>} for the pmos model. Every netlist that
    includes this file must define all ten .param values.
    """
    text = model_file.read_text()
    blocks = re.split(r"(?im)^(?=\.model)", text)
    out = []
    for block in blocks:
        m = re.match(r"(?i)\.model\s+(\w+)", block)
        if m:
            pre = "n" if m.group(1).lower() == "nmos" else "p"
            for p in config.PROC_PARAMS:
                block, n = re.subn(
                    r"(?i)(?<![\w])(%s)(\s*=\s*)([-+0-9.eE]+)" % p,
                    lambda mm, pre=pre, p=p: f"{mm.group(1)}{mm.group(2)}{{p_{pre}_{p}}}",
                    block)
                assert n == 1, f"{p} found {n} times in {pre}mos model"
        out.append(block)
    header = (f"* Parametrised copy of {model_file.name} (auto-generated by spice_utils.py)\n"
              f"* vth0, toxe, ndep, u0, xj are .param variables: p_n_* (nmos), p_p_* (pmos)\n")
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(header + "".join(out))
    return dest


def param_lines(nmos: dict, pmos: dict) -> str:
    """Two .param lines defining all ten process parameters."""
    n = " ".join(f"p_n_{k}={nmos[k]:.10g}" for k in config.PROC_PARAMS)
    p = " ".join(f"p_p_{k}={pmos[k]:.10g}" for k in config.PROC_PARAMS)
    return f".param {n}\n.param {p}\n"


# ----------------------------------------------------------------------------
# Batch runner
# ----------------------------------------------------------------------------
_PRINT_RE = re.compile(r"^\s*([\w()#:.\-@\[\]]+)\s*=\s*([-+0-9.eE]+|nan|inf)\s*$", re.I)


def run_batch(exe: str, workdir: Path, cir_names: list, print_vectors: list,
              driver_name: str) -> dict:
    """
    Run each circuit file in `cir_names` (relative to workdir) with an operating
    point analysis inside ONE ngspice process and return
    {cir_name: {vector: value}}. Circuits that fail to converge are missing.
    """
    lines = ["* batch driver (auto-generated)", ".control", "set numdgt=12"]
    vec = " ".join(print_vectors)
    for name in cir_names:
        lines += [f"source {name}", f"echo @@BEGIN {name}", "op",
                  f"print {vec}", f"echo @@END {name}", "remcirc"]
    lines += [".endc", ".end", ""]
    drv = workdir / driver_name
    drv.write_text("\n".join(lines))

    proc = subprocess.run([exe, "-b", driver_name], cwd=workdir,
                          capture_output=True, text=True)
    # stderr and stdout are separate streams, so failures are detected by the
    # missing "No. of Data Rows" marker that a successful op prints (stdout).
    results, cur, vals, ok = {}, None, {}, False
    for line in proc.stdout.splitlines():
        if line.startswith("@@BEGIN"):
            cur, vals, ok = line.split(None, 1)[1].strip(), {}, False
        elif line.startswith("@@END"):
            if cur is not None and ok and len(vals) == len(print_vectors):
                results[cur] = vals
            cur = None
        elif cur is not None:
            if "No. of Data Rows" in line:
                ok = True
                continue
            m = _PRINT_RE.match(line)
            if m:
                vals[m.group(1).lower()] = float(m.group(2))
    return results
